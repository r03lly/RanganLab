/** Hook praktis: teks antarmuka mengikuti bahasa tersimpan. */
export function useT() {
  const { lang } = useLang();
  return { lang, t: strings[lang] };
}

/** Teks tahapan praktik sesuai bahasa aktif. */
export function stepText(s: Step, lang: Lang) {
  if (lang === "id") return s;
  const en = stepsEn[s.no];
  return en ? { ...s, ...en } : s;
}
